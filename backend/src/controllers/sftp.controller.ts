import { Request, Response } from 'express'
import { z } from 'zod'
import { SftpService } from '../services/sftp.service'
import { LocalPathError, LocalPathService } from '../services/local-path.service'
import { LocalGrantError, LocalGrantService } from '../services/local-grant.service'
import { AppLockService } from '../services/app-lock.service'
import { logger } from '../services/logger.service'

// Returns the message from an unknown thrown value, falling back to undefined.
function errorMessage(error: unknown): string | undefined {
  return error instanceof Error ? error.message : undefined
}

// Progress event payload emitted by SftpService.transferEvents.
interface TransferProgress {
  transferId: string
  status: 'progress' | 'complete' | 'error' | 'cancelled'
  bytesTransferred?: number
  totalBytes?: number
  percent?: number
  message?: string
}

// ─── BL-23: request validation ──────────────────────────────────────────────

/**
 * Transfer ids are generated by the SFTP pane as `up-…` / `dn-…`. They become
 * EventEmitter event names, so anything else — `error`, `newListener`,
 * `__proto__` — is refused.
 */
const TRANSFER_ID = /^(up|dn)-[0-9a-z]{1,32}$/

export function isValidTransferId(value: unknown): value is string {
  return typeof value === 'string' && TRANSFER_ID.test(value)
}

const transferIdFor = (prefix: 'up' | 'dn'): z.ZodString =>
  z
    .string()
    .regex(
      new RegExp(`^${prefix}-[0-9a-z]{1,32}$`),
      `transferId must look like "${prefix}-" followed by 1–32 lowercase letters or digits`
    )

const remotePath = z
  .string()
  .min(1, 'Remote path required')
  .max(4096, 'Remote path is too long')
  .refine((value) => !value.includes('\0'), 'Invalid remote path')

/**
 * BL-47 / ADR-006: a local file is named by a grant the main process issued, never by a path.
 * The schemas are strict, so a `localPath` (or any other extra key) is refused.
 */
const GRANT = /^[0-9a-f]{32}$/
const grantField = z.string().regex(GRANT, 'Invalid local file grant')
const UploadLocal = z.strictObject({
  grant: grantField,
  name: z.string().min(1).max(255).optional()
})
const DownloadLocal = z.strictObject({ grant: grantField })

const ListQuerySchema = z.object({
  path: z
    .string()
    .max(4096, 'Remote path is too long')
    .refine((value) => !value.includes('\0'), 'Invalid remote path')
    .optional(),
  showHidden: z.enum(['true', 'false']).optional()
})

const UploadSchema = z.strictObject({
  local: UploadLocal,
  remotePath,
  transferId: transferIdFor('up')
})
const DownloadSchema = z.strictObject({
  remotePath,
  local: DownloadLocal,
  transferId: transferIdFor('dn')
})
const RemotePathSchema = z.object({ remotePath })
const RenameSchema = z.object({ oldPath: remotePath, newPath: remotePath })
const ChmodSchema = z.object({
  remotePath,
  mode: z.union([
    z.string().regex(/^[0-7]{3,4}$/, 'Mode must be 3–4 octal digits'),
    z.number().int().min(0).max(0o7777)
  ])
})

/** Sends `400 { error }` with the first validation issue. */
function badRequest(res: Response, error: z.ZodError): void {
  res.status(400).json({ error: error.issues[0]?.message ?? 'Invalid request' })
}

// ─── BL-18: progress streams close when the app locks ───────────────────────

const openProgressStreams = new Set<Response>()

AppLockService.onLock(() => {
  for (const stream of openProgressStreams) stream.end()
  openProgressStreams.clear()
})

// ─── Handlers ───────────────────────────────────────────────────────────────

export async function listDirectory(req: Request, res: Response): Promise<void> {
  const sessionId = req.params.sessionId as string
  const query = ListQuerySchema.safeParse(req.query)
  if (!query.success) return badRequest(res, query.error)
  const targetPath = query.data.path || '.'
  const showHidden = query.data.showHidden === 'true'

  try {
    const files = await SftpService.list(sessionId, targetPath, showHidden)
    res.json({ files })
  } catch (error: unknown) {
    res.status(500).json({ error: errorMessage(error) || 'SFTP list failed' })
  }
}

/** Answers a refused local file (400, or 503 when main could not be asked). False for other errors. */
function answerLocalFileError(res: Response, error: unknown): boolean {
  if (error instanceof LocalGrantError) {
    res.status(error.status).json({ error: error.message, code: error.code })
    return true
  }
  if (error instanceof LocalPathError) {
    res.status(400).json({ error: error.message })
    return true
  }
  return false
}

/** Shared tail of upload/download: refuse a busy id, then start the transfer in the background. */
function startTransfer(
  res: Response,
  transferId: string,
  run: () => Promise<void>,
  kind: 'Upload' | 'Download'
): void {
  if (SftpService.isTransferIdInUse(transferId)) {
    res.status(409).json({ error: 'A transfer with this id is already in progress' })
    return
  }
  run().catch((err) => logger.error(`${kind} ${transferId} failed: ${errorMessage(err) ?? err}`))
  res.json({ success: true, transferId })
}

export async function resolveRemotePath(req: Request, res: Response): Promise<void> {
  const sessionId = req.params.sessionId as string
  const query = ListQuerySchema.pick({ path: true }).safeParse(req.query)
  if (!query.success) return badRequest(res, query.error)

  try {
    res.json({ path: await SftpService.realpath(sessionId, query.data.path || '.') })
  } catch (error: unknown) {
    res.status(500).json({ error: errorMessage(error) || 'Could not resolve the path' })
  }
}

export async function uploadFile(req: Request, res: Response): Promise<void> {
  const sessionId = req.params.sessionId as string
  const body = UploadSchema.safeParse(req.body)
  if (!body.success) return badRequest(res, body.error)
  const { remotePath: target, transferId } = body.data

  let source: string
  try {
    // The main process says which file this grant names; the checks below are a second line.
    const granted = await LocalGrantService.resolve(sessionId, body.data.local, 'read')
    source = await LocalPathService.uploadSource(granted)
  } catch (error: unknown) {
    if (answerLocalFileError(res, error)) return
    throw error
  }

  startTransfer(
    res,
    transferId,
    () => SftpService.upload(sessionId, source, target, transferId),
    'Upload'
  )
}

export async function downloadFile(req: Request, res: Response): Promise<void> {
  const sessionId = req.params.sessionId as string
  const body = DownloadSchema.safeParse(req.body)
  if (!body.success) return badRequest(res, body.error)
  const { remotePath: source, transferId } = body.data

  let target: string
  try {
    const granted = await LocalGrantService.resolve(sessionId, body.data.local, 'write')
    target = await LocalPathService.downloadTarget(granted)
  } catch (error: unknown) {
    if (answerLocalFileError(res, error)) return
    throw error
  }

  startTransfer(
    res,
    transferId,
    () => SftpService.download(sessionId, source, target, transferId),
    'Download'
  )
}

export async function deleteFile(req: Request, res: Response): Promise<void> {
  const sessionId = req.params.sessionId as string
  const body = RemotePathSchema.safeParse(req.body)
  if (!body.success) return badRequest(res, body.error)

  try {
    await SftpService.deleteFile(sessionId, body.data.remotePath)
    res.json({ success: true })
  } catch (error: unknown) {
    res.status(500).json({ error: errorMessage(error) || 'Failed to delete file' })
  }
}

